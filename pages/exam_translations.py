# Validate translation completeness

for lang, values in SYLLABUS_TEXTS.items():
    if len(values) != len(SYLLABUS_KEYS):
        raise ValueError(
            f"Incomplete syllabus translation: {lang}"
        )


SYLLABUS_TRANSLATIONS = {
    lang: dict(zip(SYLLABUS_KEYS, values))
    for lang, values in SYLLABUS_TEXTS.items()
}


def topic_text(code, english=False):

    language = (
        "en" if english
        else st.session_state.get("ui_language", "en")
    )

    translations = SYLLABUS_TRANSLATIONS.get(
        language,
        SYLLABUS_TRANSLATIONS["en"]
    )

    return translations.get(
        code,
        SYLLABUS_TRANSLATIONS["en"].get(code, code)
    )
